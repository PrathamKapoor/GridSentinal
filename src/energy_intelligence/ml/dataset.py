"""The ML dataset: windows, an explicit schema, and a versioned artifact.

Representation
--------------
One flat row per ``(series, forecast origin)`` sample. This is deliberately the
simplest shape that works:

.. code-block:: text

    features           float32 (n_samples, n_features)   X
    targets            float32 (n_samples, n_horizons)   y at t+1..t+H
    horizons           tuple[int, ...]                  which target column is which step
    origin_index       int32   (n_samples,)              forecast origin on the grid
    series_index       int32   (n_samples,)              which series the row belongs to
    split              int8    (n_samples,)              0 train / 1 validation / 2 test
    series_ids         tuple[str, ...]                   row -> series name
    feature_names      tuple[str, ...]                   column -> feature name

Why flat and not nested windows: a window-per-sample ``(n_samples, lookback)``
tensor for 40 series and a 35,040-step year is gigabytes, it cannot be inspected
with ``assert``, and it ties the dataset to one model's input format. A flat matrix
plus an explicit ``origin_index`` gives every model the same information - a
sequence model reshapes it, a tabular model reads it - and every temporal
invariant can be asserted directly.

The dataset is stored as ``<name>.npz`` (arrays) beside ``<name>.json`` (the full
manifest: schema, provenance, feature definitions, split definition, quality and a
content digest). Both are regenerated by
:func:`build_dataset`; neither is hand-edited.
"""

