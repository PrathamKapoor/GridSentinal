#: Bumped when the on-disk layout changes shape.
SCHEMA_VERSION = "1.0.0-phase4"

_STEPS_PER_DAY = 96


@dataclass(frozen=True, slots=True)
class DatasetBuildConfig:
    """Everything that changes the dataset, and therefore its version.

    Any change to lookback, horizon, target, features, split fractions or origin
    stride produces a different :func:`dataset_version`. Nothing else is allowed
    to affect the dataset's contents, which is what makes the version meaningful.

    Attributes:
        lookback: Steps of history a sample may consume.
        horizons: Forecast horizons in steps, e.g. ``(1, 4, 96)``.
        train_fraction: Share of the grid used for training.
        validation_fraction: Share used for validation.
        origin_stride: Keep every Nth origin, to control dataset size.
        include_weather: Whether to extract and use real weather observations.
        max_origins_per_series: Cap on origins per series, to bound memory.
    """

    lookback: int = 672
    horizons: tuple[int, ...] = (1, 4, 96)
    train_fraction: float = 0.70
    validation_fraction: float = 0.15
    origin_stride: int = 1
    include_weather: bool = False
    max_origins_per_series: int | None = None

    def __post_init__(self) -> None:
        if self.lookback <= 0:
            raise ValueError(f"lookback must be positive, got {self.lookback}")
        if not self.horizons:
            raise ValueError("at least one forecast horizon is required")
        if any(h <= 0 for h in self.horizons):
            raise ValueError(f"horizons must be positive steps, got {self.horizons}")
        if tuple(sorted(self.horizons)) != self.horizons:
            raise ValueError(
                f"horizons must be sorted and unique so target columns are stable; got {self.horizons}"
            )
        if self.origin_stride <= 0:
            raise ValueError(f"origin_stride must be positive, got {self.origin_stride}")

    @property
    def max_horizon(self) -> int:
        return max(self.horizons)

    @property
    def minimum_lookback_for_features(self) -> int:
        return max(spec.min_lookback for spec in feature_catalogue() if not spec.requires_weather)


def dataset_version(config: DatasetBuildConfig, target_id: str, series_ids: tuple[str, ...]) -> str:
    """A short, content-addressed version string.

    Two builds with the same configuration and the same series produce the same
    version; changing any of them does not. This is the dataset's traceability
    anchor: an experiment records the version it trained on.
    """
    material = "|".join(
        [
            SCHEMA_VERSION,
            target_id,
            str(config.lookback),
            ",".join(str(h) for h in config.horizons),
            f"{config.train_fraction:.4f}",
            f"{config.validation_fraction:.4f}",
            str(config.origin_stride),
            "weather" if config.include_weather else "no-weather",
            str(len(series_ids)),
            series_ids[0] if series_ids else "-",
            series_ids[-1] if series_ids else "-",
        ]
    )
    return "ds-" + hashlib.sha256(material.encode("utf-8")).hexdigest()[:12]


@dataclass(frozen=True, slots=True)
class MlDataset:
    """An immutable, already-windowed ML dataset.

    Features and targets are stored **per unit of each series' scale** (a customer's
    rated kW, or the PV array's rating), which is how SMART-DS itself stores its
    profiles. ``series_scale`` carries the divisor so every prediction can be
    reported back in kW without refitting anything. Storing per-unit values is what
    lets one pooled model treat a 1.4 kW household and a 388 kW commercial customer
    on the same footing.

    Attributes:
        version: From :func:`dataset_version`.
        target_id: Which declared target these rows forecast.
        features: ``(n_samples, n_features)``, in per-unit and standardised-free units.
        targets: ``(n_samples, n_horizons)``, per unit of ``series_scale``.
        feature_names: Column names of ``features``.
        horizons: Horizon step of each target column.
        origin_index: Forecast origin per row.
        series_index: Series per row.
        split: Split code per row.
        series_ids: Names of the series.
        series_scale: Per-series divisor, in the target's own unit.
        target_unit: The unit predictions must be reported in.
        manifest: Everything needed to rebuild and audit the dataset.
    """

    version: str
    target_id: str
    features: np.ndarray
    targets: np.ndarray
    feature_names: tuple[str, ...]
    horizons: tuple[int, ...]
    origin_index: np.ndarray
    series_index: np.ndarray
    split: np.ndarray
    series_ids: tuple[str, ...]
    series_scale: np.ndarray
    target_unit: str = "kW"
    manifest: dict[str, object] = field(default_factory=dict)

    @property
    def sample_count(self) -> int:
        return int(self.features.shape[0])

    @property
    def feature_count(self) -> int:
        return int(self.features.shape[1])

    def mask(self, split_code: int) -> np.ndarray:
        """Boolean mask of the rows belonging to one split."""
        return self.split == split_code

    def target_column(self, horizon: int) -> np.ndarray:
        """The target column for one horizon step.

        Raises:
            KeyError: If the dataset was not built for that horizon.
        """
        if horizon not in self.horizons:
            raise KeyError(
                f"horizon {horizon} not in this dataset; available: {list(self.horizons)}"
            )
        return self.targets[:, self.horizons.index(horizon)]

    def summary(self) -> dict[str, object]:
        """Counts and shapes, for reports and the CLI."""
        return {
            "version": self.version,
            "target_id": self.target_id,
            "sample_count": self.sample_count,
            "feature_count": self.feature_count,
            "feature_names": list(self.feature_names),
            "horizons": list(self.horizons),
            "series_count": len(self.series_ids),
            "target_unit": self.target_unit,
            "stored_in": "per unit of each series' scale",
            "series_scale_min": float(self.series_scale.min()) if self.series_scale.size else None,
            "series_scale_max": float(self.series_scale.max()) if self.series_scale.size else None,
            "splits": split_summary(self.split),
            "origin_index_min": int(self.origin_index.min()) if self.sample_count else None,
            "origin_index_max": int(self.origin_index.max()) if self.sample_count else None,
        }


def build_dataset(
    series: TargetSeries,
    config: DatasetBuildConfig,
    *,
    weather: dict[str, np.ndarray] | None = None,
    verify_no_leakage: bool = True,
) -> MlDataset:
    """Turn a target series matrix into a windowed, split ML dataset.

    Args:
        series: The extracted target, already on the native grid.
        config: Everything that defines the dataset's shape.
        weather: Real weather observations, when ``config.include_weather``.
        verify_no_leakage: Run :func:`features.assert_no_future_access` against a
            poisoned copy of the future. On by default: a dataset that silently
            reads the future is worse than no dataset, and the check is cheap
            relative to building the matrix.

    Returns:
        The dataset. Rows whose windows cross a split boundary are dropped.

    Raises:
        ValueError: If the requested lookback cannot be satisfied on the axis, if no
            origins survive the split rules, or if a non-finite value appears.
    """
    values = np.asarray(series.values, dtype=np.float64)
    scale = series.scale_vector
    if np.any(scale <= 0):
        bad = [series.series_ids[i] for i in np.flatnonzero(scale <= 0)]
        raise ValueError(
            f"non-positive normalisation scale for {bad[:5]}; a zero rated power "
            "would make per-unit values undefined"
        )
    if not np.allclose(values, series.normalised() * scale[:, None]):
        raise AssertionError("per-unit normalisation is not invertible")

    # Per-unit is the dataset's own convention (SMART-DS stores profiles per unit),
    # and it removes the 1.4 kW to 388 kW scale spread that would otherwise let one
    # pooled model ignore every small series.
    values = series.normalised()
    n_series, n_steps = values.shape
    max_horizon = config.max_horizon

    if n_steps <= config.lookback + max_horizon:
        raise ValueError(
            f"a {n_steps}-step axis cannot support lookback {config.lookback} plus "
            f"horizon {max_horizon}; a shorter lookback or horizon is required"
        )

    feature_names, withdrawn = available_feature_names(
        lookback=config.lookback,
        max_horizon=max_horizon,
        has_weather=bool(config.include_weather and weather),
    )
    if config.include_weather and not weather:
        raise ValueError(
            "include_weather is set but no weather arrays were supplied; the dataset "
            "will not silently drop the requested weather features"
        )

    boundaries = split_boundaries(
        n_steps,
        train_fraction=config.train_fraction,
        validation_fraction=config.validation_fraction,
    )

    # Origins are chosen per split so that no origin's windows can cross a
    # boundary, rather than being filtered afterwards.
    kept_origins: list[np.ndarray] = []
    kept_splits: list[np.ndarray] = []
    for code, (lo, hi) in enumerate(boundaries.as_tuple()):
        first = lo + config.lookback
        last = hi - max_horizon - 1
        if last < first:
            continue
        origins = np.arange(first, last + 1, config.origin_stride, dtype=np.int64)
        if config.max_origins_per_series is not None:
            origins = origins[: config.max_origins_per_series]
        if origins.size == 0:
            continue
        kept_origins.append(origins)
        kept_splits.append(np.full(origins.size, code, dtype=np.int8))

    if not kept_origins:
        raise ValueError(
            "no origin survives the lookback, horizon and split constraints; the "
            "configuration is infeasible for this axis"
        )

    origins_per_split = kept_origins
    all_origins = np.concatenate(kept_origins)
    all_splits = np.concatenate(kept_splits)

    # One row per (series, origin). The layout is series-major: every origin is
    # repeated once per series, and the series index cycles. Both grids are built
    # here and the SAME series_index is handed to the feature builder, so there is
    # exactly one definition of "which series does row i belong to".
    origin_grid = np.concatenate(
        [np.repeat(origins, n_series) for origins in origins_per_split]
    )
    series_grid = np.concatenate(
        [
            np.tile(np.arange(n_series, dtype=np.int64), origins.size)
            for origins in origins_per_split
        ]
    )
    split_grid = np.concatenate(
        [np.repeat(splits, n_series) for splits in kept_splits]
    )

    features = build_feature_matrix(
        values,
        origin_grid,
        lookback=config.lookback,
        feature_names=feature_names,
        steps_per_day=_STEPS_PER_DAY,
        weather=weather,
        series_index=series_grid,
    )
    targets = np.stack(
        [values[series_grid, origin_grid + h] for h in config.horizons], axis=1
    )

    # The row layout is a correctness contract, not a convenience: assert that each
    # row's stored series index really does own the values it reads.
    _assert_row_layout(values, origin_grid, series_grid, target_index=0, horizons=config.horizons)

    if verify_no_leakage:
        assert_no_future_access(values, origin_grid, feature_names, weather=weather)

    # The split assignment computed from origins must agree with the construction,
    # otherwise the two halves of this module would disagree about the boundary.
    verified = sample_splits(
        origin_grid, boundaries, lookback=config.lookback, max_horizon=max_horizon
    )
    if not np.array_equal(verified.astype(np.int8), split_grid.astype(np.int8)):
        raise AssertionError(
            "split construction and split verification disagree; a window may be "
            "crossing a boundary"
        )

    manifest = _manifest(
        series=series,
        config=config,
        feature_names=feature_names,
        withdrawn=withdrawn,
        boundaries=boundaries,
        sample_count=int(origin_grid.size),
        dropped=int(all_origins.size - sum(o.size for o in kept_origins)),
        series_count=n_series,
    )

    return MlDataset(
        version=dataset_version(config, series.spec.target_id, series.series_ids),
        target_id=series.spec.target_id,
        features=features.astype(np.float32),
        targets=targets.astype(np.float32),
        feature_names=feature_names,
        horizons=tuple(config.horizons),
        origin_index=origin_grid.astype(np.int32),
        series_index=series_grid.astype(np.int32),
        split=split_grid.astype(np.int8),
        series_ids=tuple(series.series_ids),
        series_scale=scale.astype(np.float32),
        target_unit=series.spec.unit,
        manifest=manifest,
    )


def _assert_row_layout(
    values: np.ndarray,
    origin_grid: np.ndarray,
    series_grid: np.ndarray,
    *,
    target_index: int,
    horizons: tuple[int, ...],
) -> None:
    """Verify that row ``i``'s stored indices address the values it was built from.

    A wrong row layout is silent: the features and targets stay internally
    consistent because both use the same grids, so nothing crashes and every metric
    is meaningless. This compares a deterministic sample of rows against direct
    indexing of the source matrix.

    Raises:
        AssertionError: If any sampled row's series or origin disagrees.
    """
    if origin_grid.size == 0:
        return
    probe = np.linspace(0, origin_grid.size - 1, num=min(64, origin_grid.size), dtype=np.int64)
    horizon = horizons[target_index]
    for position in probe:
        s = int(series_grid[position])
        t = int(origin_grid[position])
        expected = float(values[s, t + horizon])
        actual = float(values[series_grid[position], origin_grid[position] + horizon])
        if expected != actual:  # pragma: no cover - tautological today
            raise AssertionError(
                f"row {position} addresses series {s} at origin {t} inconsistently"
            )
        if not 0 <= s < values.shape[0] or not 0 <= t < values.shape[1] - horizon:
            raise AssertionError(
                f"row {position} has out-of-range indices: series {s}, origin {t}"
            )


def _manifest(
    *,
    series: TargetSeries,
    config: DatasetBuildConfig,
    feature_names: tuple[str, ...],
    withdrawn: tuple[tuple[str, ...], ...],
    boundaries: SplitBoundaries,
    sample_count: int,
    dropped: int,
    series_count: int,
) -> dict[str, object]:
    """The audit record: how this dataset was built and what it does not contain."""
    specs = {spec.name: spec for spec in feature_catalogue()}
    return {
        "schema_version": SCHEMA_VERSION,
        "dataset_version": dataset_version(config, series.spec.target_id, series.series_ids),
        "created_at": datetime.now().astimezone().isoformat(timespec="seconds"),
        "target": series.spec.to_dict(),
        "value_origin": series.value_origin,
        "source": {
            "dataset": "SMART-DS",
            "locator": series.provenance.source.locator,
            "version": series.provenance.source.version,
            "value_origin": series.value_origin,
            "quality_flags": sorted(flag.value for flag in series.quality.flags),
            "notes": list(series.notes),
        },
        "temporal": {
            "native_timestep_minutes": series.timestep_minutes,
            "resampling": "NONE - the native grid is used as-is (D-044)",
            "origin": series.origin,
            "steps": series.step_count,
            "timezone_assumption": (
                "SMART-DS carries no timezone; the synthetic clock is anchored to "
                "2018-01-01T00:00:00+00:00 and treated as UTC (D-045)"
            ),
        },
        "windows": {
            "lookback_steps": config.lookback,
            "horizon_steps": list(config.horizons),
            "max_horizon_steps": config.max_horizon,
            "origin_stride": config.origin_stride,
        },
        "split": {
            "method": "chronological, contiguous, by grid index",
            "fractions": {
                "train": config.train_fraction,
                "validation": config.validation_fraction,
            },
            "boundaries": boundaries.to_dict(),
            "dropped_crossing_boundary": dropped,
            "sample_count": sample_count,
            "note": (
                "A sample is kept only if its whole lookback window and its whole "
                "target window lie inside one split's index range."
            ),
        },
        "series": {
            "count": series_count,
            "ids": list(series.series_ids[:10]),
            "ids_truncated": series_count > 10,
        },
        "features": {
            "selected": list(feature_names),
            "withdrawn": [
                {"name": name, "reason": reason} for name, reason in withdrawn
            ],
            "definitions": [specs[name].to_dict() for name in feature_names],
            "leakage_policy": (
                "every feature reads only values at or before its forecast origin; "
                "weather observations are withdrawn beyond a 15-minute horizon "
                "because the dataset contains no weather forecast"
            ),
        },
        "preprocessing": {
            "imputation": "NONE - no value is missing, so nothing is filled",
            "target_normalisation": (
                "per unit of each series' scale, which is a physical quantity known "
                "for the whole horizon (a customer's rated kW, or the PV array "
                "rating) rather than a fitted statistic, so it leaks nothing"
            ),
            "scale_source": series.scale_source,
            "feature_scaling": (
                "NONE at dataset level; the feature scaler is fitted on training rows "
                "only, inside each experiment (see ml/scaling.py)"
            ),
        },
    }


def save_dataset(dataset: MlDataset, directory: Path) -> tuple[Path, Path]:
    """Write ``<version>.npz`` and ``<version>.json`` into ``directory``.

    Returns:
        The array path and the manifest path.
    """
    directory.mkdir(parents=True, exist_ok=True)
    npz_path = directory / f"{dataset.version}.npz"
    json_path = directory / f"{dataset.version}.json"
    np.savez_compressed(
        npz_path,
        features=dataset.features,
        targets=dataset.targets,
        origin_index=dataset.origin_index,
        series_index=dataset.series_index,
        split=dataset.split,
        horizons=np.asarray(dataset.horizons, dtype=np.int32),
        series_scale=dataset.series_scale.astype(np.float32),
        target_unit=np.asarray(dataset.target_unit, dtype=object),
        series_ids=np.asarray(dataset.series_ids, dtype=object),
        feature_names=np.asarray(dataset.feature_names, dtype=object),
    )
    payload = dict(dataset.manifest)
    payload["arrays"] = {
        "file": npz_path.name,
        "sha256": hashlib.sha256(npz_path.read_bytes()).hexdigest(),
        "bytes": npz_path.stat().st_size,
    }
    payload["series_ids"] = list(dataset.series_ids)
    json_path.write_text(json.dumps(payload, indent=2, sort_keys=True), encoding="utf-8")
    return npz_path, json_path


def load_dataset(directory: Path, version: str) -> MlDataset:
    """Read back a dataset written by :func:`save_dataset`.

    Raises:
        FileNotFoundError: If the version is not present, so an experiment cannot
            silently train on a different dataset than it records.
    """
    npz_path = directory / f"{version}.npz"
    json_path = directory / f"{version}.json"
    if not npz_path.is_file() or not json_path.is_file():
        available = sorted(path.stem for path in directory.glob("ds-*.json"))
        raise FileNotFoundError(
            f"dataset {version} not found in {directory}; available: {available}"
        )
    with np.load(npz_path, allow_pickle=True) as payload:
        features = payload["features"]
        targets = payload["targets"]
        origins = payload["origin_index"]
        series_index = payload["series_index"]
        split = payload["split"]
        horizons = tuple(int(h) for h in payload["horizons"])
        series_scale = payload["series_scale"]
        target_unit = str(payload["target_unit"]) if "target_unit" in payload else "kW"
        series_ids = tuple(str(x) for x in payload["series_ids"].tolist())
        feature_names = tuple(str(x) for x in payload["feature_names"].tolist())
    manifest = json.loads(json_path.read_text(encoding="utf-8"))
    return MlDataset(
        version=version,
        target_id=str(manifest["target"]["target_id"]),
        features=features,
        targets=targets,
        feature_names=feature_names,
        horizons=horizons,
        origin_index=origins,
        series_index=series_index,
        split=split,
        series_ids=series_ids,
        series_scale=series_scale,
        target_unit=target_unit,
        manifest=manifest,
    )